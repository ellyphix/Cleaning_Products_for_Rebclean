-- Keep public enquiry submissions anonymous and limited to form-owned columns.
-- The preceding migrations create both tables, enable RLS, and grant INSERT.

ALTER TABLE public.contact_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.wholesale_enquiries ENABLE ROW LEVEL SECURITY;

-- Remove table and any column-level privileges from roles used by the public API.
REVOKE ALL PRIVILEGES ON TABLE public.contact_messages, public.wholesale_enquiries
  FROM PUBLIC, anon, authenticated;

REVOKE ALL PRIVILEGES (id, name, email, subject, message, created_at)
  ON TABLE public.contact_messages
  FROM PUBLIC, anon, authenticated;

REVOKE ALL PRIVILEGES (id, name, email, phone, business_name, message, created_at)
  ON TABLE public.wholesale_enquiries
  FROM PUBLIC, anon, authenticated;

-- Visitors can submit only the values collected by each form. IDs and timestamps
-- continue to be generated by their column defaults.
GRANT INSERT (name, email, subject, message)
  ON TABLE public.contact_messages TO anon;

GRANT INSERT (name, email, phone, business_name, message)
  ON TABLE public.wholesale_enquiries TO anon;

-- The website has no sign-in flow; permit only the anonymous public role.
DROP POLICY IF EXISTS "Public can submit contact messages" ON public.contact_messages;
CREATE POLICY "Public can submit contact messages"
  ON public.contact_messages FOR INSERT TO anon
  WITH CHECK (true);

DROP POLICY IF EXISTS "Public can submit wholesale enquiries" ON public.wholesale_enquiries;
CREATE POLICY "Public can submit wholesale enquiries"
  ON public.wholesale_enquiries FOR INSERT TO anon
  WITH CHECK (true);
